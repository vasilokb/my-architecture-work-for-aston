def to_pgvector(emb) -> str:
    return "[" + ", ".join(f"{x:.8f}" for x in emb) + "]"


def main():
    model = SentenceTransformer(MODEL)
    conn = psycopg2.connect(**DB)
    try:
        with conn:
            with conn.cursor() as cur:
                cur.execute("SELECT DISTINCT skill FROM vacancy_skills UNION SELECT DISTINCT skill FROM user_skills UNION SELECT name FROM skills")
                names = [r[0] for r in cur.fetchall()]
                texts = [f"{n}. {DESC[n]}" if n in DESC else n for n in names]
                embs = model.encode(texts, normalize_embeddings=True)
                for name, emb in zip(names, embs):
                    v = to_pgvector(emb)
                    cur.execute("UPDATE skills SET ctx_embedding = %s WHERE name = %s", (v, name))
                    cur.execute("UPDATE vacancy_skills SET ctx_embedding = %s WHERE skill = %s", (v, name))
                    cur.execute("UPDATE user_skills SET ctx_embedding = %s WHERE skill = %s", (v, name))
        print(f"ctx_embedding updated for {len(names)} skills")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
